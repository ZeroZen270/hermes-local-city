"""Civics (world upgrade P5): proposals, debate, all-citizen voting.

Citizens run their city. A proposal — seeded by the state of the
world (low stores, too few houses, depleted groves, a research
insight a citizen picked up) or put to the city by the player —
goes through three public acts:

  1. **Draft + debate.** A citizen proposer (rotating, chosen for
     role relevance to the seed) puts the case. When a live brain
     is wired, an LLM call drafts the title and rationale in the
     proposer's voice from their soul (card + memories + the seed
     fact); in mock mode — or when the call fails — a template draft
     from the seed stands. Two supporters and one skeptic then
     argue it, one line each, in character (LLM when live; template
     lines in mock; silence in live mode when the call fails).
  2. **The vote.** EVERY citizen casts a ballot. Per Aaron's
     directive (2026-11-24) there is no formula weighting in live
     mode: each ballot is generated by AI from that citizen's soul
     — card, their memories (past civic votes first), the proposal
     and a digest of the debate — returning FOR / AGAINST / ABSTAIN
     with a one-line reason. Ballots are cast asynchronously over a
     voting window under the same rate discipline as the ambient
     conversation generator (max 2 in flight, a small start gap,
     background threads, results drained on the world tick). A
     ballot call that returns garbage is retried once, then the
     citizen ABSTAINs with reason "no clear answer"; a call that
     hard-fails (exception) ABSTAINs with "couldn't be reached" —
     in live mode there is NO rule-based ballot fallback, ever.
     Rule ballots from role/trait affinity exist ONLY in mock/demo
     mode (no ballot caster wired), as the documented demo path —
     the standalone web client mirrors exactly that path in JS.
  3. **The outcome.** A majority of FOR over AGAINST among cast
     ballots (abstains excluded) adopts the proposal. Every citizen
     — voter, abstainer, the unreached — gets a kind="civic" memory
     of the outcome and their own vote, so soul-fed conversation can
     reference it later. An adopted proposal executes through the
     EXISTING systems: a construction site placed by the building
     rules near the named anchor, a terrain crew job, new tree
     resource nodes, or a temporary raise of the foreman's stock
     targets — or, for an "expand" proposal (P9), the land itself
     growing by one ring plus flatten crews on the new district's
     plots. A rejected proposal executes nothing.

The player (god) may propose and may close a vote early, but gets
NO ballot and cannot override the tally.

The engine is owned by WorldBridge and ticked from the tail of
ActivityPlanner.tick — the same loop that drives work, building
and terraforming — reading the same wired worlds off the planner
(resources / construction / terrain). It never moves anyone and
writes nothing but civic memories and the world's own systems.
"""
