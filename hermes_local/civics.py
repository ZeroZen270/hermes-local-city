def action_summary(action: dict) -> str:
    """One plain phrase for what a proposal would DO."""
    kind = action.get("type")
    if kind == "build":
        name = BUILDINGS.get(action.get("kind"), {}).get("name",
                                                         action.get("kind"))
        return f"build a {name} near {action.get('anchor', 'the city')}"
    if kind == "terraform":
        verb = "dig a pond" if action.get("op") == "lower" \
            else "flatten the ground"
        return f"{verb} near {action.get('anchor', 'the city')}"
    if kind == "plant_trees":
        return (f"plant {action.get('count', 4)} oak trees near "
                f"{action.get('anchor', 'the city')}")
    if kind == "gather_drive":
        return (f"run a gathering drive: raise the "
                f"{action.get('resource', 'food')} target by "
                f"{action.get('extra', GATHER_DRIVE_EXTRA)} for "
                f"{int(action.get('duration', GATHER_DRIVE_S) // 60)} "
                f"minutes")
    if kind == "adopt_innovation":
        return (f"adopt a citizen's discovery into the world: "
                f"{action.get('innovation_hint', 'something new')} — "
                f"researched, developed and made real for citizens "
                f"to make, use and trade")
    if kind == "asset":
        return (f"commission a designed asset for the city: "
                f"{action.get('asset_hint', 'something beautiful')} "
                f"— drawn by the city's designers, validated, and "
                f"placed in the world if the design holds up")
    if kind == "expand":
        return ("expand the city — open a new ring of land with "
                "fresh districts, fields and building plots")
    return "an unknown work"


class CivicsEngine:
    """Proposals, debate and the all-citizen vote for one city.

    Wiring: WorldBridge constructs the engine with the planner (the
    worlds hang off it) and sets `planner.civics`; build_world then
    swaps in the live generators for live worlds. With no ballot
    caster wired the engine is in mock/demo mode: template drafts,
    template debate, rule ballots."""

    def __init__(self, planner, layout_objects_fn=None,
                 knowledge_fn=None):
        self.planner = planner
        self.npcs = planner.npcs
        self._layout_objects = layout_objects_fn or (lambda: [])
        # The bridge's shared city knowledge (research.py): insight
        # entries carrying an innovation_hint seed adopt_innovation
        # proposals, proposed by the citizen who did the research.
        self._knowledge_fn = knowledge_fn or (lambda: [])
        self._innovation_seen: set = set()    # knowledge ids seeded
        # Live generators (world_bridge.make_civic_generators):
        #   drafter(card, soul_text, seed) -> (title, rationale)|None
        #   debater(cards, soul_texts, proposal) -> [(name, line)]|None
        #   ballot_caster(card, soul_text, proposal, debate_digest)
        #       -> (choice, reason)|None   (raises on hard failure)
        self.drafter = None
        self.debater = None
        self.ballot_caster = None
        # True only when build_world wired the live ballot caster.
        # Rule ballots are used ONLY when this is False — a live
        # world whose caster fails gets "couldn't be reached"
        # abstains, never a formula vote.
        self.ai_ballots = False
        self.rng = random.Random(23)
        self.current: dict | None = None      # the open proposal
        self.history: list[dict] = []         # decided proposals
        self._seq = 0
        self._seed_next: float | None = None
        self._asset_seed_mark = 0     # prosperity level last seeded (P8)
        self._proposer_cursor = 0
        self._research_seen: set = set()      # insight texts seeded
        self._results: queue.Queue = queue.Queue()
        self._ballot_queue: list[str] = []
        self._ballot_inflight = 0
        self._ballot_lock = threading.Lock()
        self._ballot_last_at = -1e9
        self._positions: dict = {}

    # -- world access ----------------------------------------------------
    @property
    def memory(self):
        for npc in self.npcs.values():
            store = getattr(npc, "memory", None)
            if store is not None:
                return store
        return None

    def _anchor(self, name):
        """A planner anchor by name (exact, then substring), or None."""
        anchors = self.planner.anchors if self.planner else []
        for a in anchors:
            if a.name == name:
                return a
        low = str(name or "").lower()
        for a in anchors:
            if low and low in a.name.lower():
                return a
        return None

    def _soul_text(self, card, limit: int = 4) -> str:
        """A citizen's soul as prompt text: their past civic votes
        first (how they decided before is who they are now), then a
        research insight if they hold one, then their most recent
        memories. Mirrors the conversation generator's soul-feeding,
        civic-aware."""
        memory = self.memory
        if memory is None:
            return ""
        try:
            entries = memory.list_namespace(card.namespace)
        except Exception:
            return ""
        if not entries:
            return ""
        picked: list[str] = []

        def take(pool):
            for entry in pool:
                text = " ".join(str(entry.get("text", "")).split())
                if text and text not in picked:
                    picked.append(text)
                if len(picked) >= limit:
                    return

        take([e for e in reversed(entries) if e.get("kind") == "civic"])
        take([e for e in reversed(entries)
              if e.get("kind") == "research"])
        take(list(reversed(entries)))
        if not picked:
            return ""
        return "\n".join(f"- {t[:160]}" for t in picked)

    # -- public views ------------------------------------------------------
    def _tally(self, prop: dict) -> dict:
        tally = {"for": 0, "against": 0, "abstain": 0,
                 "cast": len(prop["ballots"]),
                 "total": len(self.npcs)}
        for ballot in prop["ballots"].values():
            tally[ballot["choice"].lower()] += 1
        return tally

    def public(self, prop: dict) -> dict:
        return {"id": prop["id"], "proposer": prop["proposer"],
                "title": prop["title"], "rationale": prop["rationale"],
                "action": dict(prop["action"]), "state": prop["state"],
                "tally": self._tally(prop),
                "ballots": [{"name": name, **ballot} for name, ballot
                            in prop["ballots"].items()],
                "debate": [dict(d) for d in prop["debate"]]}

    def public_state(self) -> dict:
        """The Civics panel / interpreter view: the open proposal
        (with its live tally) plus the recent outcomes."""
        return {"open": self.public(self.current)
                if self.current is not None else None,
                "history": [{"id": h["id"], "proposer": h["proposer"],
                             "title": h["title"],
                             "outcome": h["state"],
                             "tally": h["tally"],
                             "executed": h.get("executed")}
                            for h in self.history[-HISTORY_KEEP:]]}

    # -- opening proposals ---------------------------------------------------
    def validate_action(self, action):
        """Normalize a proposed action against the world's rules, or
        explain why it cannot be put to the city. Returns
        (clean_action, None) or (None, human_reason)."""
        if not isinstance(action, dict):
            return None, "A proposal needs an action object."
        kind = action.get("type")
        if kind not in ACTION_TYPES:
            return None, ("A proposal's action must be one of: "
                          + ", ".join(ACTION_TYPES) + ".")
        clean = {"type": kind}
        if kind == "build":
            bk = str(action.get("kind", ""))
            if bk not in BUILDINGS:
                return None, ("Unknown building "
                              f"{bk!r} — want one of: "
                              + ", ".join(BUILDINGS) + ".")
            clean["kind"] = bk
        if kind in ("build", "terraform", "plant_trees"):
            anchor = self._anchor(action.get("anchor"))
            if anchor is None:
                return None, (f"No place named "
                              f"{action.get('anchor')!r} in this city.")
            clean["anchor"] = anchor.name
        if kind == "terraform":
            op = str(action.get("op", "flatten"))
            if op not in ("flatten", "lower"):
                return None, ("Civic earthworks are 'flatten' (level "
                              "a plot) or 'lower' (dig a pond).")
            clean["op"] = op
            clean["radius"] = min(16.0, max(4.0, float(
                action.get("radius", 10.0))))
            clean["amount"] = min(1.6, max(0.4, float(
                action.get("amount", 1.0))))
        if kind == "plant_trees":
            clean["count"] = min(8, max(1, int(
                action.get("count", 4))))
        if kind == "gather_drive":
            resource = str(action.get("resource", "food"))
            if resource not in ("wood", "food"):
                return None, "A gathering drive targets wood or food."
            clean["resource"] = resource
            clean["extra"] = min(10, max(2, int(
                action.get("extra", GATHER_DRIVE_EXTRA))))
            clean["duration"] = min(1800.0, max(300.0, float(
                action.get("duration", GATHER_DRIVE_S))))
        if kind == "adopt_innovation":
            hint = " ".join(str(
                action.get("innovation_hint")
                or action.get("hint") or "").split())
            if not hint:
                return None, ("An innovation proposal needs an "
                              "'innovation_hint' — the discovery "
                              "the city would adopt.")
            clean["innovation_hint"] = hint[:120]
        if kind == "asset":
            hint = " ".join(str(
                action.get("asset_hint")
                or action.get("hint") or "").split())
            if not hint:
                return None, ("An asset proposal needs an "
                              "'asset_hint' — the thing the city "
                              "would have designed and placed.")
            clean["asset_hint"] = hint[:120]
        if kind == "expand":
            # Growth (P9) takes no parameters: the vote IS the act.
            # At the engine cap there is nothing to put to the city.
            ter = self.planner.terrain if self.planner else None
            if ter is not None and ter.bound >= _TERRAIN_MAX_BOUND:
                return None, ("The city already spans the widest "
                              "ground this world can hold — there "
                              "is no further ring to vote on.")
        return clean, None

    def open_proposal(self, proposer: str, title: str, rationale: str,
                      action: dict, now: float, seed: dict | None = None):
        """Put a proposal before the city. Returns (events, None) or
        (None, human_reason) — one open proposal at a time."""
        if self.current is not None:
            return None, ("The city is still deciding on "
                          f"'{self.current['title']}' — one proposal "
                          "at a time.")
        clean, reason = self.validate_action(action)
        if clean is None:
            return None, reason
        self._seq += 1
        prop = {"id": f"prop-{self._seq}", "proposer": proposer,
                "title": (title or "").strip()
                         or self._template_title(clean, seed),
                "rationale": (rationale or "").strip()
                             or self._template_rationale(clean, seed,
                                                         proposer),
                "action": clean, "state": "open",
                "ballots": {}, "debate": [], "created_at": now,
                "seed": seed, "phase": "draft",
                "phase_at": now, "force_close": False}
        self.current = prop
        return [self._proposal_event(prop)], None

    def request_close_vote(self):
        """The Keeper ends the voting window early. The tally stands
        as cast — closing never changes a single ballot."""
        prop = self.current
        if prop is None or prop["state"] != "voting":
            return False, "No vote is underway to close."
        prop["force_close"] = True
        return True, ("The Keeper called the vote closed — the "
                      "tally stands as cast.")

    def _proposal_event(self, prop: dict, updated: bool = False) -> dict:
        ev = {"type": "proposal", "id": prop["id"],
              "proposer": prop["proposer"], "title": prop["title"],
              "rationale": prop["rationale"], "state": prop["state"],
              "action_type": prop["action"]["type"],
              "proposal": self.public(prop)}
        if updated:
            ev["updated"] = True
        return ev

    # -- templates (mock mode + live failure path for drafts) ----------------
    def _template_title(self, action: dict, seed: dict | None) -> str:
        if seed:
            kind = seed.get("kind")
            if kind == "low_food":
                return "A food drive for the city stores"
            if kind == "low_wood":
                return "A wood drive for the city stores"
            if kind == "few_houses":
                return "A new house for the city"
            if kind == "depleted_groves":
                return "Replant the groves"
            if kind == "pond":
                return "Dig a pond for the city"
            if kind == "research":
                if action.get("type") == "adopt_innovation":
                    return (f"Adopt the discovery: "
                            f"{action.get('innovation_hint', '')}")
                return "Act on a citizen's discovery"
            if kind == "prosperity":
                return (f"Beautify the city: "
                        f"{action.get('asset_hint', '')}")
            if kind == "crowded":
                return "Room to grow: expand the city"
        return {"build": "A building proposal",
                "terraform": "An earthworks proposal",
                "plant_trees": "A planting proposal",
                "gather_drive": "A gathering drive",
                "adopt_innovation": "Adopt a discovery",
                "asset": "A designed asset for the city",
                "expand": "Expand the city"}[action["type"]]

    def _template_rationale(self, action: dict, seed: dict | None,
                            proposer: str) -> str:
        fact = (seed or {}).get("fact", "")
        base = f"{proposer} proposes the city {action_summary(action)}."
        return f"{fact} {base}".strip()

    def _template_debate(self, prop: dict, supporters, skeptic):
        fact = (prop.get("seed") or {}).get("fact", "")
        summary = action_summary(prop["action"])
        lines = []
        if len(supporters) >= 1:
            lines.append((supporters[0],
                          f"I'm for it. {fact or 'The need is plain.'} "
                          f"Let's {summary}."))
        if len(supporters) >= 2:
            card = self.npcs[supporters[1]].card
            lines.append((supporters[1],
                          f"As a {card.role} I see it up close — "
                          f"{prop['proposer']} is right. Count me in."))
        if skeptic:
            lines.append((skeptic,
                          f"Hold on — {_WORRY[prop['action']['type']]}. "
                          "Are we sure this is the best use of our "
                          "hands?"))
        return lines

    # -- role affinity (debate casting + mock rule ballots only) -------------
    def _affinity(self, card, action_type: str) -> float:
        score = _ROLE_SCORE.get(action_type, {}).get(card.role, 0.0)
        for trait in card.traits or []:
            score += _TRAIT_SCORE.get(action_type, {}).get(trait, 0.0)
        return score

    def _rule_ballot(self, card, prop: dict):
        """The DEMO path: a ballot from role/trait affinity. Used
        only when no AI ballot caster is wired (mock/standalone) —
        live worlds never see this function."""
        rng = random.Random(f"{prop['id']}:{card.name}")
        score = self._affinity(card, prop["action"]["type"]) \
            + rng.uniform(-0.5, 0.5)
        summary = action_summary(prop["action"])
        if score >= 0.75:
            reason = rng.choice([
                f"As a {card.role}, I see the good in it — yes.",
                "It answers a real need. I'm for it.",
                "We've put this off long enough — let's do it."])
            return "FOR", reason
        if score <= -0.35:
            reason = rng.choice([
                "The cost isn't worth it — I'm against it.",
                f"A {card.role} learns care with big changes — no.",
                "Not convinced this is the right fix."])
            return "AGAINST", reason
        return "ABSTAIN", "No strong feelings either way."

    # -- the seed engine -------------------------------------------------------
    def _pick_proposer(self, seed_kind: str, holder: str | None = None):
        names = sorted(self.npcs)
        if holder and holder in self.npcs:
            return holder
        roles = _PROPOSER_ROLES.get(seed_kind, ())
        pool = [n for n in names
                if self.npcs[n].card.role in roles] or names
        pick = pool[self._proposer_cursor % len(pool)]
        self._proposer_cursor += 1
        return pick

    def _consider_seed(self, now: float):
        """Read the world and, if something wants doing, draft the
        next proposal from it. Priority: a fresh research insight,
        empty stores, too few houses, depleted groves, a pond."""
        planner = self.planner
        resources = planner.resources
        seed = None
        # A researched discovery with an innovation hint (P6): the
        # insight's holder proposes adopting it into the world —
        # the innovation loop's front door. City knowledge entries
        # are the structured source; each is seeded at most once.
        try:
            knowledge = self._knowledge_fn() or []
        except Exception:
            knowledge = []
        hinted_summaries = set()
        for entry in knowledge:
            if not isinstance(entry, dict):
                continue
            if entry.get("summary"):
                hinted_summaries.add(
                    " ".join(str(entry["summary"]).split()))
            hint = entry.get("innovation_hint")
            if not hint or seed is not None:
                continue
            key = entry.get("id") or entry.get("summary") or hint
            if key in self._innovation_seen:
                continue
            self._innovation_seen.add(key)
            holder = entry.get("citizen")
            seed = {"kind": "research",
                    "holder": holder if holder in self.npcs else None,
                    "action": {"type": "adopt_innovation",
                               "innovation_hint": str(hint)[:120]},
                    "fact": (f"{holder or 'A citizen'} researched "
                             f"\"{entry.get('question', '')}\" at "
                             f"the terminal and learned: "
                             f"{str(entry.get('summary', ''))[:140]}")}
        # A citizen's research insight without a hint (P6 feeds
        # kind="research" memories; the seed reads them if
        # present) still stirs the city to build.
        memory = self.memory
        if seed is None and memory is not None:
            for name in sorted(self.npcs):
                card = self.npcs[name].card
                try:
                    entries = memory.list_namespace(card.namespace)
                except Exception:
                    continue
                for entry in reversed(entries):
                    if entry.get("kind") != "research":
                        continue
                    text = " ".join(str(entry.get("text", "")).split())
                    if not text or text in self._research_seen:
                        continue
                    if any(s and s in text for s in hinted_summaries):
                        continue    # a hinted insight: handled above
                    self._research_seen.add(text)
                    houses = self._house_count()
                    action = ({"type": "build", "kind": "stall",
                               "anchor": "Market Row West"}
                              if houses >= 2 else
                              {"type": "build", "kind": "house",
                               "anchor": self._front_anchor_name()})
                    seed = {"kind": "research", "holder": name,
                            "action": action,
                            "fact": (f"{name} learned something at "
                                     f"the research terminal: "
                                     f"\"{text[:140]}\"")}
                    break
                if seed:
                    break
        inv = resources.inventory if resources is not None else {}
        targets = planner.effective_targets(now) \
            if hasattr(planner, "effective_targets") else \
            {"wood": work_mod.TARGET_WOOD, "food": work_mod.TARGET_FOOD}
        if seed is None and resources is not None \
                and inv.get("food", 0) < targets["food"]:
            seed = {"kind": "low_food",
                    "action": {"type": "gather_drive",
                               "resource": "food"},
                    "fact": (f"The city stores hold "
                             f"{inv.get('food', 0)} food against a "
                             f"target of {targets['food']} — shelves "
                             "are thinning.")}
        if seed is None and resources is not None \
                and inv.get("wood", 0) < targets["wood"]:
            seed = {"kind": "low_wood",
                    "action": {"type": "gather_drive",
                               "resource": "wood"},
                    "fact": (f"The city stores hold "
                             f"{inv.get('wood', 0)} wood against a "
                             f"target of {targets['wood']} — the "
                             "sawbench will idle soon.")}
        if seed is None and self._house_count() < 2:
            seed = {"kind": "few_houses",
                    "action": {"type": "build", "kind": "house",
                               "anchor": self._front_anchor_name()},
                    "fact": ("The city still has barely a house to "
                             "its name — citizens double up and "
                             "grumble about it.")}
        if seed is None and resources is not None:
            trees = [n for n in resources.nodes.values()
                     if n.kind == "tree"]
            depleted = [n for n in trees if n.stock < n.max_stock]
            if len(depleted) >= 5:
                grove = "Old Park" if self._proposer_cursor % 2 == 0 \
                    else "North Green"
                seed = {"kind": "depleted_groves",
                        "action": {"type": "plant_trees", "count": 5,
                                   "anchor": grove},
                        "fact": (f"{len(depleted)} of the city's "
                                 f"{len(trees)} oaks stand felled or "
                                 "young — the groves are thinning.")}
        if seed is None and planner.terrain is not None \
                and self.rng.random() < 0.5:
            from .terrain import WATER_Y
            heights = planner.terrain.heights
            if heights and min(heights) > WATER_Y:
                seed = {"kind": "pond",
                        "action": {"type": "terraform", "op": "lower",
                                   "anchor": "Old Park",
                                   "radius": 10.0, "amount": 1.0},
                        "fact": ("Not a pond nor puddle in the whole "
                                 "city — on hot days there is nowhere "
                                 "to cool off.")}
        if seed is None and planner.terrain is not None \
                and planner.construction is not None \
                and planner.terrain.bound < _TERRAIN_MAX_BOUND:
            # Crowding (P9): a city that has built itself full —
            # EXPANSION_SEED_THRESHOLD finished buildings + open
            # sites — starts wanting ROOM. Growth is a civic act:
            # the seed proposes it, the citizens vote on it, and an
            # adopted vote grows the land itself (see _execute).
            built = len(planner.construction.buildings) \
                + sum(1 for s in planner.construction.sites.values()
                      if not s.complete)
            if built >= EXPANSION_SEED_THRESHOLD:
                seed = {"kind": "crowded",
                        "action": {"type": "expand"},
                        "fact": (f"{built} buildings stand or are "
                                 f"rising and every plot in the old "
                                 f"city is spoken for — the streets "
                                 f"feel crowded and there is nowhere "
                                 f"left to build.")}
        if seed is None:
            # Prosperity (P8): a city whose market trades and whose
            # skyline grows starts wanting beauty, not just stores.
            # One asset proposal per prosperity level (25 trade or
            # 3 finished buildings past the last one seeded) — a
            # thriving city beautifies itself at a measured pace.
            inno = getattr(planner, "innovations", None)
            trade = inno.trade if inno is not None else 0
            built = len(planner.construction.buildings) \
                if planner.construction is not None else 0
            level = trade // ASSET_TRADE_STEP \
                + built // ASSET_BUILDING_STEP
            if level > self._asset_seed_mark:
                self._asset_seed_mark = level
                hint = ASSET_HINTS[(level - 1) % len(ASSET_HINTS)]
                seed = {"kind": "prosperity",
                        "action": {"type": "asset",
                                   "asset_hint": hint},
                        "fact": (f"The market has traded {trade} "
                                 f"in goods and {built} buildings "
                                 f"stand finished — the city is "
                                 f"thriving, and its squares are "
                                 f"still bare.")}
        if seed is None:
            return None
        proposer = self._pick_proposer(seed["kind"],
                                       seed.get("holder"))
        events, _reason = self.open_proposal(
            proposer, "", "", seed["action"], now, seed=seed)
        return events

    def _house_count(self) -> int:
        con = self.planner.construction
        if con is None:
            return 0
        return sum(1 for b in con.buildings if b.get("kind") == "house") \
            + sum(1 for s in con.sites.values() if s.kind == "house")

    def _front_anchor_name(self) -> str:
        for a in self.planner.anchors:
            if a.kind == "front":
                return a.name
        return "Central Plaza"

    # -- the tick ---------------------------------------------------------------
    def tick(self, now: float, positions: dict) -> list[dict]:
        """Advance civics one world tick: drain finished LLM work,
        walk the open proposal through draft -> debate -> voting ->
        outcome, and consider a new seed when the city is quiet."""
        self._positions = positions or {}
        events: list[dict] = []
        events.extend(self._drain_results(now))
        prop = self.current
        if prop is None:
            if self._seed_next is None:
                self._seed_next = now + SEED_INTERVAL_S
            elif now >= self._seed_next:
                self._seed_next = now + SEED_INTERVAL_S
                seeded = self._consider_seed(now)
                if seeded:
                    events.extend(seeded)
            return events
        phase = prop["phase"]
        if phase == "draft":
            events.extend(self._phase_draft(prop, now))
        elif phase == "debate":
            if now - prop["phase_at"] >= DEBATE_WAIT_S:
                self._begin_voting(prop, now, events)   # debate skipped
        elif phase == "voting":
            self._service_ballots(prop, now)
            self._maybe_close(prop, now, events)
        return events

    def _phase_draft(self, prop: dict, now: float) -> list[dict]:
        """Seed proposals get one live drafting pass (the proposer's
        own voice over the template); player proposals and mock mode
        go straight to debate."""
        events: list[dict] = []
        if prop.get("seed") is None or self.drafter is None:
            self._begin_debate(prop, now, events)
            return events
        if not prop.get("draft_started"):
            prop["draft_started"] = True
            card = self.npcs[prop["proposer"]].card
            soul = self._soul_text(card)
            drafter, seed = self.drafter, dict(prop["seed"])

            def work():
                try:
                    result = drafter(card, soul, seed)
                except Exception:
                    result = None
                self._results.put({"kind": "draft", "id": prop["id"],
                                   "result": result})

            threading.Thread(target=work, daemon=True,
                             name="hermes-civic-draft").start()
            return events
        if now - prop["phase_at"] >= DRAFT_WAIT_S:
            # The draft never landed: the template stands (the spec's
            # failure path) and the city moves on.
            self._begin_debate(prop, now, events)
        return events

    def _begin_debate(self, prop: dict, now: float,
                      events: list[dict]) -> None:
        prop["phase"] = "debate"
        prop["phase_at"] = now
        prop["state"] = "debating"
        # Cast the debate by role relevance: the two citizens who
        # gain most argue for, the least convinced argues against.
        others = [n for n in sorted(self.npcs)
                  if n != prop["proposer"]]
        scored = sorted(
            others,
            key=lambda n: (-self._affinity(self.npcs[n].card,
                                           prop["action"]["type"]), n))
        supporters = scored[:2]
        skeptic = scored[-1] if len(scored) > 2 else None
        prop["debaters"] = supporters + ([skeptic] if skeptic else [])
        if self.debater is None:
            if not self.ai_ballots:
                # Mock/demo: template lines, in character by role.
                lines = self._template_debate(prop, supporters, skeptic)
                self._land_debate(prop, lines, events)
                self._begin_voting(prop, now, events)
            else:
                # Live world, no debate hook wired: skip the debate.
                self._begin_voting(prop, now, events)
            return
        cards = [self.npcs[n].card for n in prop["debaters"]]
        souls = {n: self._soul_text(self.npcs[n].card)
                 for n in prop["debaters"]}
        debater = self.debater
        public = self.public(prop)

        def work():
            try:
                result = debater(cards, souls, public)
            except Exception:
                result = None
            self._results.put({"kind": "debate", "id": prop["id"],
                               "result": result})

        threading.Thread(target=work, daemon=True,
                         name="hermes-civic-debate").start()

    def _land_debate(self, prop: dict, lines, events: list[dict]) -> None:
        for name, text in lines or []:
            if name not in self.npcs or not str(text).strip():
                continue
            line = {"npc": name, "text": str(text).strip()[:200]}
            prop["debate"].append(line)
            events.append({"type": "debate", "proposal": prop["id"],
                           "npc": name, "text": line["text"],
                           "stance": "against" if prop["debaters"]
                           and name == prop["debaters"][-1]
                           and len(prop["debaters"]) > 2 else "for"})

    def _begin_voting(self, prop: dict, now: float,
                      events: list[dict]) -> None:
        prop["phase"] = "voting"
        prop["phase_at"] = now
        prop["state"] = "voting"
        prop["vote_deadline"] = now + VOTE_WINDOW_S
        if self.ai_ballots and self.ballot_caster is not None:
            self._ballot_queue = [n for n in sorted(self.npcs)
                                  if n not in prop["ballots"]]
            return
        # Mock/demo: rule ballots, cast at once, then the outcome.
        for name in sorted(self.npcs):
            choice, reason = self._rule_ballot(self.npcs[name].card,
                                               prop)
            self._record_ballot(prop, name, choice, reason, events)
        self._close(prop, now, events)

    def _service_ballots(self, prop: dict, now: float) -> None:
        """Start ballot calls under the ambient discipline: at most
        BALLOT_MAX_INFLIGHT running, a small gap between starts,
        each on its own daemon thread."""
        while self._ballot_queue:
            with self._ballot_lock:
                if self._ballot_inflight >= BALLOT_MAX_INFLIGHT:
                    return
            if now - self._ballot_last_at < BALLOT_GAP_S:
                return
            name = self._ballot_queue.pop(0)
            self._ballot_last_at = now
            with self._ballot_lock:
                self._ballot_inflight += 1
            card = self.npcs[name].card
            caster = self.ballot_caster
            public = self.public(prop)
            debate_digest = "\n".join(
                f"{d['npc']}: {d['text']}" for d in prop["debate"])

            def work(name=name, card=card):
                try:
                    soul = self._soul_text(card)
                    result = caster(card, soul, public, debate_digest)
                    if result is None:
                        # Garbage back: one retry, then the citizen
                        # is recorded as having no clear answer.
                        result = caster(card, soul, public,
                                        debate_digest)
                    if result is None:
                        choice, reason = "ABSTAIN", "no clear answer"
                    else:
                        choice, reason = result
                        if choice not in CHOICES:
                            choice, reason = "ABSTAIN", "no clear answer"
                except Exception:
                    # Hard failure: the citizen could not be reached.
                    # NO rule ballot is ever substituted in live mode.
                    choice, reason = "ABSTAIN", "couldn't be reached"
                try:
                    self._results.put({"kind": "ballot",
                                       "id": prop["id"], "name": name,
                                       "choice": choice,
                                       "reason": str(reason)[:160]})
                finally:
                    with self._ballot_lock:
                        self._ballot_inflight -= 1

            threading.Thread(target=work, daemon=True,
                             name="hermes-civic-ballot").start()

    def _record_ballot(self, prop: dict, name: str, choice: str,
                       reason: str, events: list[dict]) -> None:
        if name in prop["ballots"]:
            return
        prop["ballots"][name] = {"choice": choice, "reason": reason}
        events.append({"type": "ballot", "proposal": prop["id"],
                       "name": name, "choice": choice,
                       "reason": reason})

    def _maybe_close(self, prop: dict, now: float,
                     events: list[dict]) -> None:
        total = len(self.npcs)
        cast = len(prop["ballots"])
        if cast >= total:
            self._close(prop, now, events)
        elif prop.get("force_close"):
            self._close(prop, now, events)
        elif now >= prop.get("vote_deadline", 0.0) \
                and total and cast / total >= VOTE_MIN_CAST:
            self._close(prop, now, events)

    def _close(self, prop: dict, now: float,
               events: list[dict]) -> None:
        # Citizens the window closed on are recorded as abstaining —
        # every citizen ends up holding a ballot, and every citizen
        # remembers the vote.
        for name in sorted(self.npcs):
            if name not in prop["ballots"]:
                self._record_ballot(
                    prop, name, "ABSTAIN",
                    "the vote closed before they answered", events)
        tally = self._tally(prop)
        adopted = tally["for"] > tally["against"]
        prop["state"] = "adopted" if adopted else "rejected"
        prop["phase"] = "done"
        prop["tally"] = tally
        executed = None
        if adopted:
            exec_events, executed = self._execute(prop, now)
            events.extend(exec_events)
        prop["executed"] = executed
        outcome = prop["state"].upper()
        for name, npc in self.npcs.items():
            ballot = prop["ballots"].get(
                name, {"choice": "ABSTAIN", "reason": ""})
            npc.witness(
                f"The city voted on '{prop['title']}' (proposed by "
                f"{prop['proposer']}): {outcome}, "
                f"{tally['for']} for, {tally['against']} against, "
                f"{tally['abstain']} abstaining. I voted "
                f"{ballot['choice']} — {ballot['reason']}",
                kind="civic")
        events.append({"type": "civic_result", "proposal": prop["id"],
                       "title": prop["title"],
                       "proposer": prop["proposer"],
                       "outcome": prop["state"], "tally": tally,
                       "executed": executed})
        self.history.append(prop)
        self.current = None
        self._ballot_queue = []
        self._seed_next = now + SEED_INTERVAL_S

    def _drain_results(self, now: float) -> list[dict]:
        events: list[dict] = []
        while True:
            try:
                res = self._results.get_nowait()
            except queue.Empty:
                break
            prop = self.current
            if prop is None or res.get("id") != prop["id"]:
                continue    # stale work from a decided proposal
            if res["kind"] == "draft" and prop["phase"] == "draft":
                result = res.get("result")
                if result:
                    title, rationale = result
                    if title:
                        prop["title"] = str(title)[:120]
                    if rationale:
                        prop["rationale"] = str(rationale)[:400]
                    events.append(self._proposal_event(prop,
                                                       updated=True))
                self._begin_debate(prop, now, events)
            elif res["kind"] == "debate" and prop["phase"] == "debate":
                lines = res.get("result")
                if lines:
                    self._land_debate(prop, lines, events)
                # Live failure = no debate (silence), never templates.
                self._begin_voting(prop, now, events)
            elif res["kind"] == "ballot" and prop["phase"] == "voting":
                self._record_ballot(prop, res["name"], res["choice"],
                                    res["reason"], events)
        return events

    # -- executing an adopted proposal through the existing systems -----------
    def _execute(self, prop: dict, now: float):
        """Run the adopted action. Returns (events, executed_text) —
        the events are the systems' own (build placed / terraform
        job created), so clients and the interpreter see the work
        exactly as if the player had ordered it."""
        planner = self.planner
        action = prop["action"]
        kind = action["type"]
        if kind == "build":
            con = planner.construction
            if con is None:
                return [], "the city has no construction crews"
            anchor = self._anchor(action["anchor"])
            objects = self._layout_objects()
            for ox, oz in _SPOT_OFFSETS:
                x, z = anchor.x + ox, anchor.z + oz
                if con.validate_placement(action["kind"], x, z,
                                          objects) is not None:
                    continue
                site, _reason = con.place(action["kind"], x, z,
                                          layout_objects=objects)
                if site is not None:
                    return [con.placed_event(site)], \
                        (f"a construction site for the "
                         f"{site.name.lower()} was marked out near "
                         f"{anchor.name}")
            return [], (f"no clear plot could be found near "
                        f"{action['anchor']} — the work waits")
        if kind == "terraform":
            ter = planner.terrain
            if ter is None:
                return [], "the city has no land crews"
            anchor = self._anchor(action["anchor"])
            reason = ter.validate_op(action["op"], anchor.x, anchor.z,
                                     action["radius"],
                                     action["amount"])
            if reason is not None:
                return [], f"the land refused the work: {reason}"
            target = ter.sample(anchor.x, anchor.z) \
                if action["op"] == "flatten" else None
            job = ter.create_job(action["op"], anchor.x, anchor.z,
                                 action["radius"], action["amount"],
                                 target)
            # The foreman staffs open crew jobs on its interval.
            return [ter.job_event(job, "created")], \
                (f"a citizen crew took on the {action['op']} work "
                 f"near {anchor.name}")
        if kind == "plant_trees":
            resources = planner.resources
            if resources is None:
                return [], "the city has no groves to plant"
            anchor = self._anchor(action["anchor"])
            # Planting range follows the LIVE bound (P9): a grown
            # city plants in its new districts too.
            limit = (planner.terrain.bound - 8.0) \
                if planner.terrain is not None else 112.0
            planted = 0
            taken = [(n.x, n.z) for n in resources.nodes.values()]
            for ox, oz in _SPOT_OFFSETS:
                if planted >= action["count"]:
                    break
                x, z = anchor.x + ox, anchor.z + oz
                if abs(x) > limit or abs(z) > limit:
                    continue
                if any(abs(x - c) < 7.5 or abs(z - c) < 7.5
                       for c in (-96, -48, 0, 48, 96)):
                    continue        # not on a road
                if any((x - tx) ** 2 + (z - tz) ** 2 < 6.25
                       for tx, tz in taken):
                    continue        # not on top of another node
                node_id = f"tree-civic-{prop['id']}-{planted + 1}"
                resources.nodes[node_id] = _make_node(
                    node_id, "tree", "Oak tree", x, z)
                taken.append((x, z))
                planted += 1
            if planted:
                return [], (f"{planted} young oaks were planted near "
                            f"{anchor.name}")
            return [], (f"no open ground could be found near "
                        f"{action['anchor']} for planting")
        if kind == "gather_drive":
            planner.boost_targets(action["resource"], action["extra"],
                                  action["duration"], now)
            targets = planner.effective_targets(now)
            return [], (f"the foreman's {action['resource']} target "
                        f"is raised to {targets[action['resource']]} "
                        f"for {int(action['duration'] // 60)} minutes "
                        f"— the drive is on")
        if kind == "adopt_innovation":
            # P6: the innovation engine researches the discovery
            # deeply, synthesizes + validates a content spec, and
            # registers it live (or files it under study). The
            # synthesis lands asynchronously; the civic result
            # reports that the work was taken up.
            engine = getattr(planner, "innovations", None)
            if engine is None:
                return [], ("the city has no research workshop to "
                            "develop the idea in")
            return engine.adopt(prop, now)
        if kind == "asset":
            # P8: the design engine draws the voted asset — a
            # brain-designed composition, validated like every
            # synthesis, placed as a world prop when it holds up
            # (or shelved, honestly, when it doesn't). The design
            # lands asynchronously, like an adoption.
            engine = getattr(planner, "designs", None)
            if engine is None:
                return [], ("the city has no designers to draw "
                            "the work")
            return engine.adopt_asset(prop, now)
        if kind == "expand":
            # Growth (P9, Addendum 3): the vote IS the act — the
            # land expands the moment the city adopts it. Then two
            # citizen crews set out to level building plots in the
            # newest district (the East and West anchors of the new
            # ring) through the ordinary terraform job machinery;
            # the foreman staffs them like any crew job.
            ter = planner.terrain
            if ter is None:
                return [], "the city has no land to grow into"
            info = planner.apply_expansion()
            if info is None:
                return [], ("the land can grow no further — the "
                            "city already spans the widest ground "
                            "this world can hold")
            names = ring_district_names(info["ring"])
            events = [TerrainWorld.expansion_event(
                info, names, by="civic vote")]
            specs = {name: (x, z) for name, _k, x, z
                     in district_anchor_specs(info["ring"])}
            jobs = 0
            for name in names:
                if not (name.startswith("East")
                        or name.startswith("West")):
                    continue
                x, z = specs[name]
                if ter.validate_op("flatten", x, z, 12.0, 1.0) \
                        is not None:
                    continue
                job = ter.create_job("flatten", x, z, 12.0, 1.0)
                events.append(ter.job_event(job, "created"))
                jobs += 1
            return events, (
                f"the city grew — {', '.join(names)} joined the "
                f"world, and {jobs} land crews set out to level "
                f"building plots there")
        return [], None

    # -- persistence (P7: the world-data snapshot) ---------------------------
    def _serialize_prop(self, prop: dict, decided: bool = False) -> dict:
        """One proposal as snapshot data: identity, case, action,
        debate and every ballot cast so far. Runtime machinery
        (phase timers, generation threads, the ballot queue) is
        deliberately NOT part of it — a restored open proposal
        resumes in voting state (see restore())."""
        out = {"id": prop["id"], "proposer": prop["proposer"],
               "title": prop["title"], "rationale": prop["rationale"],
               "action": dict(prop["action"]), "state": prop["state"],
               "ballots": {name: {"choice": b["choice"],
                                  "reason": b["reason"]}
                           for name, b in prop["ballots"].items()},
               "debate": [{"npc": d["npc"], "text": d["text"]}
                          for d in prop["debate"]],
               "created_at": prop.get("created_at", 0.0)}
        if decided:
            out["executed"] = prop.get("executed")
        return out

    def serialize(self) -> dict:
        """The civics slice of a world snapshot: the decided
        history plus the open proposal (or None)."""
        return {"history": [self._serialize_prop(h, decided=True)
                            for h in self.history],
                "open": (self._serialize_prop(self.current)
                         if self.current is not None else None)}

    def _clean_prop(self, raw, decided: bool) -> dict:
        """Validate one serialized proposal (snapshot restore).
        Raises ValueError on anything structural; ballots/debate
        entries naming non-citizens are dropped, and a history
        entry's tally is recomputed from its ballots rather than
        trusted."""
        if not isinstance(raw, dict):
            raise ValueError("civics proposal must be an object")
        for field in ("id", "proposer", "title"):
            if not isinstance(raw.get(field), str) \
                    or not raw[field]:
                raise ValueError(
                    f"civics proposal needs a non-empty {field!r}")
        clean_action, reason = self.validate_action(
            raw.get("action"))
        if clean_action is None:
            raise ValueError(f"civics proposal action: {reason}")
        state = raw.get("state")
        if decided and state not in ("adopted", "rejected"):
            raise ValueError(
                f"decided proposal state must be adopted/rejected, "
                f"got {state!r}")
        if not decided and state not in ("open", "debating",
                                         "voting"):
            raise ValueError(
                f"open proposal state must be open/debating/voting, "
                f"got {state!r}")
        ballots_in = raw.get("ballots") or {}
        if not isinstance(ballots_in, dict):
            raise ValueError("civics proposal ballots must be an object")
        ballots = {}
        for name, ballot in ballots_in.items():
            if name not in self.npcs or not isinstance(ballot, dict):
                continue
            choice = ballot.get("choice")
            if choice not in CHOICES:
                continue
            ballots[name] = {
                "choice": choice,
                "reason": str(ballot.get("reason") or "")[:160]}
        debate_in = raw.get("debate") or []
        if not isinstance(debate_in, list):
            raise ValueError("civics proposal debate must be a list")
        debate = [{"npc": str(d["npc"]),
                   "text": str(d.get("text") or "")[:200]}
                  for d in debate_in
                  if isinstance(d, dict) and d.get("npc") in self.npcs]
        created = raw.get("created_at")
        prop = {"id": raw["id"], "proposer": raw["proposer"],
                "title": raw["title"],
                "rationale": str(raw.get("rationale") or ""),
                "action": clean_action, "state": state,
                "ballots": ballots, "debate": debate,
                "created_at": (float(created) if isinstance(
                    created, (int, float)) else 0.0),
                "seed": None, "phase": "done" if decided else "voting",
                "phase_at": 0.0, "force_close": False}
        if decided:
            prop["executed"] = (str(raw["executed"])
                                if raw.get("executed") else None)
            prop["tally"] = self._tally(prop)
        return prop

    def validate_snapshot(self, doc) -> dict:
        """Clean the {"history", "open"} civics slice of a world
        snapshot — all-or-nothing, like the other world slices."""
        if not isinstance(doc, dict):
            raise ValueError("civics snapshot must be an object")
        history_in = doc.get("history") or []
        if not isinstance(history_in, list):
            raise ValueError("civics history must be a list")
        history = [self._clean_prop(h, decided=True)
                   for h in history_in]
        open_raw = doc.get("open")
        open_prop = (self._clean_prop(open_raw, decided=False)
                     if open_raw is not None else None)
        return {"history": history, "open": open_prop}

    def restore(self, doc, now: float) -> dict:
        """Replace the civic record from a snapshot slice
        (validated first — a malformed slice changes nothing).

        An open proposal resumes in VOTING state with its ballots
        intact: only the citizens who had not yet cast are queued
        to vote again (in-flight generation threads are not
        persisted). In the mock/demo path — no AI caster wired —
        the missing ballots are rule-cast at once, exactly as
        _begin_voting would have cast them, and the outcome lands
        on the next tick."""
        clean = self.validate_snapshot(doc)
        self.history = clean["history"][-HISTORY_KEEP:]
        self.current = None
        self._ballot_queue = []
        seq = 0
        for prop in self.history:
            seq = max(seq, self._prop_seq(prop["id"]))
        prop = clean["open"]
        if prop is not None:
            seq = max(seq, self._prop_seq(prop["id"]))
            prop["state"] = "voting"
            prop["phase"] = "voting"
            prop["phase_at"] = now
            prop["vote_deadline"] = now + VOTE_WINDOW_S
            prop["draft_started"] = True
            prop["debaters"] = []
            self.current = prop
            missing = [n for n in sorted(self.npcs)
                       if n not in prop["ballots"]]
            if self.ballot_caster is not None and self.ai_ballots:
                # Live path: re-cast ONLY the missing ballots.
                self._ballot_queue = missing
            elif not self.ai_ballots:
                # Demo path: rule ballots, as _begin_voting casts.
                for name in missing:
                    choice, reason = self._rule_ballot(
                        self.npcs[name].card, prop)
                    prop["ballots"][name] = {"choice": choice,
                                             "reason": reason}
            # (ai_ballots with no caster wired cannot happen via
            # build_world; any still-missing citizens abstain when
            # the window closes, the engine's honest failure path.)
        self._seq = max(self._seq, seq)
        self._seed_next = now + SEED_INTERVAL_S
        return {"history": len(self.history),
                "open": self.current is not None}

    @staticmethod
    def _prop_seq(prop_id) -> int:
        try:
            return int(str(prop_id).rsplit("-", 1)[1])
        except (IndexError, ValueError):
            return 0
